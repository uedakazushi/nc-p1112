#!/usr/bin/env python3
"""Build a dated Japanese PDF without overwriting an earlier build.

Run from any directory with ``python3 /path/to/repository/scripts/build.py``.
The script needs Python 3.9+, XeLaTeX, and the packages listed below.
"""

from __future__ import annotations

import argparse
from datetime import datetime
from pathlib import Path
import re
import shutil
import subprocess
import sys
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError


ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build"
REQUIRED_FILES = (
    "article.cls",
    "fontspec.sty",
    "amsmath.sty",
    "amssymb.sty",
    "amsthm.sty",
    "mathtools.sty",
    "geometry.sty",
    "hyperref.sty",
    "bookmark.sty",
    "enumitem.sty",
    "array.sty",
    "booktabs.sty",
)


def check_dependencies() -> bool:
    """Report the actual TeX search result, without modifying the installation."""
    missing_commands = [name for name in ("xelatex", "kpsewhich")
                        if shutil.which(name) is None]
    if missing_commands:
        print("Missing commands: " + ", ".join(missing_commands), file=sys.stderr)
        return False

    missing_files = []
    for name in REQUIRED_FILES:
        result = subprocess.run(
            ["kpsewhich", name], cwd=ROOT, text=True, capture_output=True,
            check=False,
        )
        if result.returncode != 0 or not result.stdout.strip():
            missing_files.append(name)
    if missing_files:
        print("TeX cannot locate the following required files:", file=sys.stderr)
        for name in missing_files:
            print(f"  {name}", file=sys.stderr)
        print(
            "Install a current TeX Live with XeLaTeX "
            "and the listed LaTeX packages. If those files are already installed, "
            "check the TeX filename database with your TeX distribution's tools.",
            file=sys.stderr,
        )
        return False
    print("XeLaTeX and all required packages are available.")
    print("The document will check its Japanese fonts through fontspec.")
    return True


def reserve_jobname(timestamp: datetime) -> str:
    """Reserve a new basename; a same-second rebuild receives a revision suffix."""
    basename = "nc_p1112_" + timestamp.strftime("%Y%m%d_%H%M%S")
    revision = 1
    while True:
        candidate = basename if revision == 1 else f"{basename}_r{revision}"
        if not any(BUILD.glob(candidate + ".*")):
            return candidate
        revision += 1


def build() -> int:
    if not (ROOT / "main.tex").is_file():
        print("The repository root does not contain main.tex.", file=sys.stderr)
        return 1
    if not check_dependencies():
        return 1
    try:
        timezone = ZoneInfo("Asia/Tokyo")
    except ZoneInfoNotFoundError:
        print("Python's timezone database lacks Asia/Tokyo; install tzdata.",
              file=sys.stderr)
        return 1

    BUILD.mkdir(exist_ok=True)
    lock = BUILD / ".build.lock"
    try:
        lock_file = lock.open("x", encoding="utf-8")
    except FileExistsError:
        print(
            "A build lock already exists at build/.build.lock. "
            "Wait for the running build; if it was interrupted, remove only "
            "that lock after confirming that no build is running.",
            file=sys.stderr,
        )
        return 1

    try:
        with lock_file:
            timestamp = datetime.now(timezone)
            jobname = reserve_jobname(timestamp)
            filename = jobname + ".pdf"
            displayed_time = timestamp.strftime("%Y-%m-%d %H:%M:%S")
            displayed_time += " JST（Asia/Tokyo）"
            lock_file.write(jobname + "\n")
            lock_file.flush()
            metadata = (
                "% Generated by scripts/build.py; do not edit.\n"
                "\\newcommand{\\BuildTimestamp}{" + displayed_time + "}\n"
                "\\newcommand{\\BuildFilename}{\\detokenize{" + filename + "}}\n"
            )
            (BUILD / "build_info.tex").write_text(metadata, encoding="utf-8")
            # Preserve the metadata corresponding to each dated PDF as well.
            (BUILD / (jobname + ".build_info.tex")).write_text(
                metadata, encoding="utf-8",
            )

            command = [
                "xelatex", "-interaction=nonstopmode", "-halt-on-error",
                "-file-line-error", "-no-shell-escape", "-recorder",
                "-output-directory=build", "-jobname=" + jobname, "main.tex",
            ]
            console_log = BUILD / (jobname + ".console.log")
            with console_log.open("w", encoding="utf-8") as stream:
                for pass_number in range(1, 4):
                    print(f"XeLaTeX pass {pass_number}/3: {filename}", flush=True)
                    stream.write(f"\nXeLaTeX pass {pass_number}/3\n")
                    stream.flush()
                    result = subprocess.run(
                        command, cwd=ROOT, stdout=stream,
                        stderr=subprocess.STDOUT, check=False,
                    )
                    if result.returncode:
                        print(f"XeLaTeX failed. See {console_log}", file=sys.stderr)
                        return result.returncode

            pdf = BUILD / filename
            if not pdf.is_file() or pdf.stat().st_size == 0:
                print("XeLaTeX did not produce a nonempty PDF.", file=sys.stderr)
                return 1
            log_path = BUILD / (jobname + ".log")
            log_text = log_path.read_text(encoding="utf-8", errors="replace")
            unresolved = re.search(
                r"There were undefined (?:references|citations)|"
                r"(?:Reference|Citation) .+ undefined|"
                r"Label\(s\) may have changed|"
                r"Rerun to get cross-references right|"
                r"Please \(re\)run Biber|"
                r"Missing character:",
                log_text,
            )
            if unresolved:
                print(
                    "The PDF was produced, but references or glyphs still need "
                    f"attention. Inspect {log_path} before using it.",
                    file=sys.stderr,
                )
                return 1
            if "Overfull \\hbox" in log_text or "Overfull \\vbox" in log_text:
                print(f"Layout warning: inspect overfull boxes in {log_path}.")
            print(f"Built {pdf}")
            print("Inspect the rendered pages before distributing the PDF.")
            return 0
    finally:
        lock.unlink(missing_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="check TeX dependencies without creating files")
    options = parser.parse_args()
    return (0 if check_dependencies() else 1) if options.check else build()


if __name__ == "__main__":
    raise SystemExit(main())
